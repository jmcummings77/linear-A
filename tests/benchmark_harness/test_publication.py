"""Public artifacts retain reproducible measurements without local host identity."""
import copy
import json
from pathlib import Path
import sys
import unittest

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "benchmarks"))
from publication import PublicSanitizer


class PublicationTests(unittest.TestCase):
    def setUp(self):
        self.sanitizer = PublicSanitizer(root="/Users/alice/My Repos/linear-A", home="/Users/alice")

    def test_project_paths_keep_spaces_lines_and_multiple_stack_frames(self):
        source = "multiply (/Users/alice/My Repos/linear-A/ports/go/my matrix.go:12:4) called by main (/tmp/private-build/src/runtime/proc.go:44:2)"
        expected = "multiply (ports/go/my matrix.go:12:4) called by main (src/runtime/proc.go:44:2)"
        self.assertEqual(self.sanitizer.text(source), expected)
        self.assertEqual(self.sanitizer.text(expected), expected)
        encoded = "file:///Users/alice/My%20Repos/linear-A/ports/wasm/matrix.mjs:10:2"
        self.assertEqual(self.sanitizer.text(encoded), "ports/wasm/matrix.mjs:10:2")
        self.assertEqual(self.sanitizer.text(encoded.replace("%20", "%2520")), "ports/wasm/matrix.mjs:10:2")

    def test_windows_drive_unc_and_file_urls_remove_host_roots(self):
        sanitizer = PublicSanitizer(root=r"C:\Users\Alice\My Repos\linear-A", home=r"C:\Users\Alice")
        self.assertEqual(sanitizer.text(r"function(C:\Users\Alice\My Repos\linear-A\ports\c\matrix.c:31:9)"),
                         "function(ports/c/matrix.c:31:9)")
        self.assertEqual(sanitizer.text("file:///C:/Users/Alice/My%20Repos/linear-A/ports/c/matrix.c:31"),
                         "ports/c/matrix.c:31")
        self.assertEqual(sanitizer.text(r"main(\\PRIVATE-PC\build share\tools\matrix.dll:12)"), "main(matrix.dll:12)")

    def test_external_libraries_preserve_source_context_without_cache_locations(self):
        examples = {
            "~/.rustup/toolchains/private/lib/rustlib/src/rust/library/alloc/src/vec/mod.rs:13:0": "library/alloc/src/vec/mod.rs:13:0",
            "/Users/alice/cache/node_modules/package/src/index.js:3:4": "node_modules/package/src/index.js:3:4",
            "/opt/private-sdk/lib/runtime.dylib": "runtime.dylib",
            "/Users/alice/private/scripts/setup.py": "setup.py",
        }
        for source, expected in examples.items():
            with self.subTest(source=source):
                self.assertEqual(self.sanitizer.text(source), expected)

    def test_public_module_identities_and_nonpath_symbols_are_unchanged(self):
        for value in ("github.com/alice/linear-A/ports/go.(*Matrix).Multiply",
                      "https://github.com/alice/linear-A", "operator/(Matrix const&)",
                      "</script><script>alert('x')</script>", "checksum = -123.5; commit 0123456789abcdef0123456789abcdef01234567"):
            with self.subTest(value=value):
                self.assertEqual(self.sanitizer.text(value), value)
        self.assertEqual(self.sanitizer.text("error for alice in /tmp/sdk/src/alice/matrix.rs:3"),
                         "error for [user] in src/[user]/matrix.rs:3")

    def test_credentials_environment_and_machine_identifiers_are_removed(self):
        source = ("HOME=/Users/alice PATH=/private/tmp/tool/bin AUTH_TOKEN=private-value "
                  "Authorization: Bearer bearer-value; host=private-mac username=alice "
                  "machine_id=01234567-89ab-cdef-0123-456789abcdef "
                  "https://alice:private-password@example.test/download?token=query-secret "
                  "ghp_abcdefghijklmnopqrstuvwxyz12345 "
                  "sk-proj-abcdefghijklmnopqrstuvwxyz12345 "
                  "AKIAABCDEFGHIJKLMNOP "
                  "Generated by Codex; elapsed=123.25 git=0123456789abcdef0123456789abcdef01234567")
        sanitized = self.sanitizer.text(source)
        for private in ("alice", "/private/tmp", "private-value", "bearer-value", "private-mac",
                        "01234567-89ab-cdef-0123-456789abcdef", "private-password", "query-secret",
                        "ghp_", "sk-proj-", "AKIA", "Codex"):
            self.assertNotIn(private, sanitized)
        self.assertIn("elapsed=123.25", sanitized)
        self.assertIn("0123456789abcdef0123456789abcdef01234567", sanitized)
        self.assertEqual(self.sanitizer.text(sanitized), sanitized)

    def test_commands_accept_path_objects_and_keep_compiler_flags(self):
        command = [Path("/private/tmp/sdk/bin/python3.9"),
                   Path("/Users/alice/My Repos/linear-A/ports/wasm/build.py"),
                   "--output=/Users/alice/My Repos/linear-A/.build/wasm",
                   "-DMATRIX_USE_ASM=1", "-sALLOW_MEMORY_GROWTH=1", "-O3",
                   "--api-key", "private-secret"]
        expected = ["python3", "ports/wasm/build.py", "--output=.build/wasm",
                    "-DMATRIX_USE_ASM=1", "-sALLOW_MEMORY_GROWTH=1", "-O3",
                    "--api-key", "[redacted]"]
        cleaned = self.sanitizer.command(command)
        self.assertEqual(cleaned, expected)
        self.assertEqual(self.sanitizer.command(cleaned), cleaned)
        self.assertEqual(self.sanitizer.command([r"C:\sdk\dotnet.exe", "--version"]), ["dotnet", "--version"])
        self.assertEqual(self.sanitizer.command(["/tmp/sdk/clang++-18", "-O3"]), ["clang++", "-O3"])

    def test_local_path_detection_distinguishes_browser_resource_urls(self):
        for path in ("file:///Users/alice/file.js", r"C:\Users\Alice\file.js", "/private/tmp/sdk/file.js",
                     "/Users/alice/My Repos/linear-A/ports/wasm/matrix.mjs", "~/private/file.js"):
            self.assertTrue(self.sanitizer.is_local_path(path), path)
        for path in ("/assets/matrix.wasm", "matrix.wasm", "https://github.com/alice/project"):
            self.assertFalse(self.sanitizer.is_local_path(path), path)

    def test_schema_allowlist_preserves_numbers_versions_and_public_provenance(self):
        measurement = {"elapsed_ns": 98884333, "iterations": 17450, "checksum": -56712.5,
                       "ns_per_op": 5666.723954154728}
        data = {
            "schema_version": 1, "created_at": "2026-10-02T12:34:56+00:00",
            "revision": "0123456789abcdef0123456789abcdef01234567", "dirty": True,
            "source_sha256": "abcdef01" * 8, "suite": "full", "seed": 17, "total_seconds": 123.456789,
            "env": {"HOME": "/Users/alice", "TOKEN": "secret"}, "agent_name": "Codex",
            "machine": {"os": "Darwin", "release": "25.5.0", "architecture": "arm64", "logical_cpus": 8,
                        "cpu_model": "Apple M2", "memory_bytes": 17179869184, "hostname": "private-mac",
                        "uuid": "01234567-89ab-cdef-0123-456789abcdef", "username": "alice"},
            "methodology": {"timing": "monotonic timer", "env": {"secret": "secret"}},
            "implementations": [{"id": "rust", "name": "Rust", "status": "passed",
                                 "toolchain": "rustc 1.69.0 (84c898d65 2023-04-16)",
                                 "detail": "owned f64 matrices", "agent": "Codex",
                                 "build_commands": [["/Users/alice/.cargo/bin/cargo", "build", "--release"]],
                                 "checks": [{"name": "fractional multiply", "passed": True,
                                             "env": {"TOKEN": "secret"}}]}],
            "results": [{"implementation": "rust", "operation": "multiply", "size": 64,
                         "status": "passed", "iterations": 17450, "samples": [measurement],
                         "median_ns": measurement["ns_per_op"], "min_ns": 5500.125, "max_ns": 5800.25,
                         "mad_ns": 0.125, "credentials": "secret"}],
            "profiles": [{"implementation": "rust", "status": "available", "chronological": False,
                          "stacks": [["matrix::multiply (/Users/alice/My Repos/linear-A/ports/rust/src/lib.rs:12)"]],
                          "weights": [0.123456789], "raw_file": "profiles/rust/sample.txt",
                          "workload": {"operation": "multiply", "size": 48, "iterations": 100, "seed": 17, "host": "private-mac"},
                          "note": "sampled stacks", "env": {"SECRET": "secret"}}],
        }
        original = copy.deepcopy(data)
        cleaned = self.sanitizer.report(data)
        self.assertEqual(data, original)
        self.assertEqual(cleaned["results"][0]["samples"][0], measurement)
        for field in ("created_at", "revision", "source_sha256", "total_seconds", "seed", "dirty"):
            self.assertEqual(cleaned[field], data[field])
        self.assertEqual(cleaned["implementations"][0]["toolchain"], data["implementations"][0]["toolchain"])
        self.assertEqual(cleaned["profiles"][0]["weights"], data["profiles"][0]["weights"])
        self.assertEqual(cleaned["machine"], {key: data["machine"][key] for key in
                         ("os", "release", "architecture", "logical_cpus", "cpu_model", "memory_bytes")})
        serialized = json.dumps(cleaned)
        for private in ("alice", "/Users/", "private-mac", "01234567-89ab-cdef-0123-456789abcdef", "Codex", "secret", '"env"'):
            self.assertNotIn(private, serialized)
        self.assertEqual(self.sanitizer.report(cleaned), cleaned)
        cleaned["results"][0]["samples"][0]["checksum"] = 999
        self.assertEqual(data, original)


if __name__ == "__main__":
    unittest.main()
